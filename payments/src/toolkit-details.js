// Also serialized into the same-origin LIVE client bundle. Use DOM text nodes,
// never HTML from a product title or catalog response. Unknown products stay hidden.
export const TOOLKIT_RENDER_JS = String.raw`function renderToolkitDetails(document, productId, product, language, details, labels) {
  const container = document.getElementById('toolkitDetails');
  if (!container) return;
  container.replaceChildren();
  container.hidden = true;
  const entry = Object.hasOwn(details, productId || '') ? details[productId] : null;
  if (!product || !entry || product.title !== entry.title) return;
  const lang = Object.hasOwn(labels, language) ? language : 'en';
  const t = labels[lang];
  const add = (parent, tag, text) => {
    const node = document.createElement(tag);
    node.textContent = text;
    parent.appendChild(node);
    return node;
  };
  const heading = add(container, 'h2', t.title);
  heading.id = 'toolkitDetailsHeading';
  add(container, 'p', t.format).className = 'hint';
  entry.text[lang].forEach((text, index) => {
    const section = document.createElement('section');
    add(section, 'h3', t.sections[index]);
    add(section, 'p', text);
    if (index === 0) add(section, 'p', entry.counts.map((count, i) => count + ' ' + t.files[i]).join(' · ')).className = 'hint';
    container.appendChild(section);
  });
  const before = document.createElement('details');
  add(before, 'summary', t.before);
  for (const text of [t.requirements, t.usage, t.validation]) add(before, 'p', text);
  container.appendChild(before);
  container.hidden = false;
}`;
